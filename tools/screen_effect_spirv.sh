#!/bin/sh
# Regenerates screen_effect_spirv.h from shaders/screen_effect.{vert,frag}.
# The SPIR-V is checked in so the build needs no shader compiler. Needs
# glslangValidator (glslang-tools), or the Flatpak SDK's:
#   GLSLANG="flatpak run --command=glslangValidator org.freedesktop.Sdk//25.08" tools/screen_effect_spirv.sh
set -e
cd "$(dirname "$0")/.."
GLSLANG=${GLSLANG:-glslangValidator}
tmp=$(mktemp -d ./.spirv.XXXXXX)   # inside the checkout: a Flatpak sandbox sees it
$GLSLANG -V --target-env vulkan1.1 --vn SCREEN_EFFECT_VERT_SPIRV -o "$tmp/vert.h" shaders/screen_effect.vert
$GLSLANG -V --target-env vulkan1.1 --vn SCREEN_EFFECT_FRAG_SPIRV -o "$tmp/frag.h" shaders/screen_effect.frag
{
    echo "#pragma once"
    echo ""
    echo "// Generated by tools/screen_effect_spirv.sh from shaders/screen_effect.{vert,frag}: don't edit."
    echo ""
    echo "#include <cstdint>"
    echo ""
    grep -v -e '^[[:space:]]*//' -e '^[[:space:]]*#pragma' "$tmp/vert.h" | sed 's/^const uint32_t/static const uint32_t/'
    echo ""
    grep -v -e '^[[:space:]]*//' -e '^[[:space:]]*#pragma' "$tmp/frag.h" | sed 's/^const uint32_t/static const uint32_t/'
} > screen_effect_spirv.h
rm -rf "$tmp"
